  SLEEP = "HYPNOSIS",
  CONFUSION = "CONFUSE_RAY"
}

local function statusAnimation(move)
  local effect = tostring(move and move.effect or ""):upper()
  if effect == "BURN_SIDE_EFFECT1" or effect == "BURN_SIDE_EFFECT2" then
    return STATUS_ANIMS.BURN
  end
  if effect == "FREEZE_SIDE_EFFECT1" then
    return STATUS_ANIMS.FREEZE
  end
  if effect == "PARALYZE_EFFECT" or effect == "PARALYZE_SIDE_EFFECT1"
      or effect == "PARALYZE_SIDE_EFFECT2" then
    return STATUS_ANIMS.PARALYZE
  end
  if effect == "POISON_EFFECT" or effect == "POISON_SIDE_EFFECT1"
      or effect == "POISON_SIDE_EFFECT2" then
    return STATUS_ANIMS.POISON
  end
  if effect == "SLEEP_EFFECT" then
    return STATUS_ANIMS.SLEEP
  end
  if effect == "CONFUSION_EFFECT" or effect == "CONFUSION_SIDE_EFFECT" then
    return STATUS_ANIMS.CONFUSION
  end
  return nil
end

local function animationForMove(move)
  if not move then return nil end

  local name = tostring(move.name or move.id or ""):upper():gsub("[^A-Z]", "")
  local isDamaging = (tonumber(move.power) or 0) > 0

  -- A non-damaging move should never receive a physical/special attack
  -- animation merely because its type is elemental. Status-inflicting moves
  -- are the exception: use the visual associated with the status itself.
  local nonDamagingAnim = STATUS_ANIMS[move.id]
  if not isDamaging then
    if nonDamagingAnim then return nonDamagingAnim end
    return statusAnimation(move)
  end

  -- For damaging moves, an explicit elemental word in the name takes
  -- priority over the mechanical/visual family. For example, Ice Beam and
  -- Fire Punch must use the Ice and Fire palettes even though "Beam" and
  -- "Punch" have their own animation families.
  local elementalWords = {
    "FIRE","FLAME","WATER","AQUA","ELECTRIC","THUNDER","GRASS","LEAF",
    "ICE","FROST","POISON","ACID","GROUND","EARTH","ROCK","STONE","BUG",
    "FLYING","AIR","PSYCHIC","PSY","GHOST","SHADOW","DRAGON","DARK",
    "STEEL","FAIRY"
  }
  for _, word in ipairs(elementalWords) do
    if name:find(word, 1, true) then
      return ELEMENTAL_NAME_ANIMS[word]
    end
  end

  if move.id and MOVE_ANIMS[move.id] then return MOVE_ANIMS[move.id] end

  -- Semantic fallback for future National Dex additions.
  if name:find("SLASH") or name:find("SCISSOR") then return "SLASH" end
  if name:find("PUNCH") then return "MEGA_PUNCH" end
  if name:find("KICK") then return "MEGA_KICK" end
  if name:find("BITE") or name:find("FANG") then return "BITE" end
  if name:find("BEAM") or name:find("BLAST") then return "HYPER_BEAM" end
  if name:find("TACKLE") or name:find("SLAM") then return "TACKLE" end
  return TYPE_ANIMS[move.type]
end

local function hasNativeAnimation(battle, moveId)
  local data = battle and battle.data
  local anims = data and data.moveAnims
  return type(anims) == "table" and anims[moveId] ~= nil
end

return function(mod)
  if not mod.find("battle_effect_colors") then
    mod.log:error("Battle Effect Colors - National Dex Support requires battle_effect_colors")
    return
  end
  if not mod.find("national_dex") then
    mod.log:error("Battle Effect Colors - National Dex Support requires national_dex")
    return
  end

  if BattleState.nationalDexBattleEffectAnimationsInstalled then return end

  local original = BattleState.performMove

  function BattleState:performMove(user, target, moveInst, isCalled)
    local move = moveInst and self:moveDef(moveInst)
    local moveId = move and move.id
    local moveType = move and move.type

    original(self, user, target, moveInst, isCalled)

    -- Never replace an animation that the base game already supplies.
    -- This makes the companion additive: National Dex moves get a fallback,
    -- while the original 165 Gen 1 moves retain their authentic animations.
    if not moveId or not moveType or hasNativeAnimation(self, moveId) then
      return
    end

    local fallback = animationForMove(move)
    local row = self.moveAnimRow

    -- Charge/failure paths may intentionally cancel the normal move animation.
    -- Only redirect the ordinary queued move row when it is still present.
    if fallback and row and row.anim == moveId then
      row.anim = fallback
    end
  end

  BattleState.nationalDexBattleEffectAnimationsInstalled = true
  mod.log:info("National Dex battle animation fallbacks installed")
end
