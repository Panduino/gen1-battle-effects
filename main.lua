local STATUS_ANIMS = {
  -- Gen 1 has a dedicated non-attack Ice/field animation: MIST.
  -- Use it for non-damaging Ice effects instead of reusing ICE_BEAM.
  AURORAVEIL = "MIST",
  HAIL = "MIST",
